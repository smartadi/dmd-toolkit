def test_kernel_dmd_linear_produces_valid_spectrum():
    """Linear kernel gives a well-defined spectrum on real data (Lorenz).
    The linear kernel can't fit chaotic dynamics, but eigenvalues must be
    finite and shapes correct.
    """
    X, t = dmd.data.lorenz(n_steps=300, dt=0.01)
    k = dmd.kernel_dmd(X, kernel="linear", rank=3, dt=0.01)
    assert k.eigenvalues.shape[0] == 3
    assert np.all(np.isfinite(np.abs(k.eigenvalues)))
    assert k.modes.shape == (3, 3)


def test_kernel_dmd_rbf_reconstructs_lorenz():
    """RBF kernel DMD should reconstruct the training portion of Lorenz
    significantly better than chance (normalised error well below 1).
    """
    X, t = dmd.data.lorenz(n_steps=300, dt=0.01)
    k = dmd.kernel_dmd(X, kernel="rbf", rank=20, dt=0.01)
    rec = k.reconstruct(t)
    rel = np.linalg.norm(rec - X, "fro") / np.linalg.norm(X, "fro")
    assert rel < 0.5, f"RBF kernel DMD reconstruction error {rel:.3e}"


def test_kernel_dmd_eigenfunctions_on_train_match_attribute():
    X, t = dmd.data.lorenz(n_steps=300, dt=0.01)
    k = dmd.kernel_dmd(X, kernel="rbf", rank=8, dt=0.01)
    phi_train_recomputed = k.eigenfunctions(X[:, :-1])
    assert phi_train_recomputed.shape == k.eigenfunctions_train.shape
    assert np.allclose(phi_train_recomputed, k.eigenfunctions_train, atol=1e-8)


def test_kernel_dmd_polynomial():
    X, t = dmd.data.lorenz(n_steps=300, dt=0.01)
    k = dmd.kernel_dmd(X, kernel="poly", rank=6, dt=0.01, degree=2, coef0=1.0)
    assert k.eigenvalues.shape[0] == 6
    rec = k.reconstruct(t)
    assert rec.shape == X.shape


def test_kernel_dmd_rank_fraction():
    X, t = dmd.data.lorenz(n_steps=300, dt=0.01)
    k = dmd.kernel_dmd(X, kernel="rbf", rank=0.99, dt=0.01)
    assert k.eigenvalues.shape[0] >= 1
